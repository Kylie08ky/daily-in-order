import test from 'node:test';
import assert from 'node:assert/strict';
import {emptyState,validateState} from '../lib/model.ts';
import {applyCommand} from '../lib/commands.ts';
import {activityStats} from '../lib/life-metrics.ts';
import {learningCategories,learningCategoryLabel,learningCategoryValue} from '../lib/learning.ts';
const now=new Date('2026-11-03T12:00:00Z');
const apply=(s,type,payload)=>applyCommand(s,{type,payload},now);
const save=(s,record)=>apply(s,'life.save',{table:'courses',record});
test('custom subjects support course progress, practice scheduling, completion and backup restore',()=>{
 let s=save(emptyState(),{id:'math',name:'高等数学',category:'工程 / 数学',total:24,initial:2,unit:'章'});
 s=save(s,{id:'code',name:'Python 实践',mode:'practice',category:'编程实践',total:null});
 s=apply(s,'task.save',{id:'practice-task',task:{title:'编程练习',date:'2026-11-03',start:'10:00',minutes:45,activity:{kind:'german',refId:'code',category:'编程实践'}}});
 assert.equal(activityStats(s,'german','code').minutes,0);
 s=apply(s,'task.progress',{id:'practice-task',progress:100,actual:40});
 s=apply(s,'life.save',{table:'entries',record:{id:'math-entry',kind:'german',refId:'math',date:'2026-11-03',minutes:30,units:1}});
 assert.equal(activityStats(s,'german','code').minutes,40);
 assert.equal(activityStats(s,'german','math').units,1);
 assert.equal(activityStats(s,'german').minutes,70);
 assert.match(s.tasks.find(t=>t.id==='activity:math-entry').title,/^学习 · /);
 s=save(s,{...s.life.courses.find(c=>c.id==='code'),category:'软件工程'});
 const restored=validateState(JSON.parse(JSON.stringify(s)));
 assert.equal(activityStats(restored,'german').minutes,70);
 assert.equal(restored.life.courses.find(c=>c.id==='math').initial+activityStats(restored,'german','math').units,3);
 assert.deepEqual(learningCategories(restored.life.courses),[['工程 / 数学','工程 / 数学'],['软件工程','软件工程']]);
 assert.throws(()=>save(s,{id:'bad',name:'超长分类',category:'长'.repeat(41),total:10}));
});
test('legacy learning categories and links survive edits and importing older data',()=>{
 let s=save(emptyState(),{id:'old',name:'旧课程',category:'listening',total:64,initial:4});
 s=apply(s,'life.save',{table:'entries',record:{id:'old-entry',kind:'german',refId:'old',date:'2026-11-03',minutes:20,units:1}});
 s=validateState(JSON.parse(JSON.stringify(s)));
 assert.equal(learningCategoryLabel(s.life.courses[0].category),'听力');
 assert.equal(learningCategoryValue('听力'),'listening');
 assert.equal(learningCategoryValue('  自选专业  '),'自选专业');
 assert.equal(learningCategoryValue(''),'other');
 assert.equal(s.life.courses[0].initial+activityStats(s,'german','old').units,5);
 assert.equal(activityStats(s,'german','old').minutes,20);
 assert.deepEqual(learningCategories([{...s.life.courses[0],deletedAt:now.toISOString()}]),[]);
 assert.deepEqual(learningCategories(emptyState().life.courses),[]);
});
